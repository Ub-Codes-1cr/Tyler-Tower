function rimTarget(theta, lane) {
  const h = 8.7; // just outside the 16x16 slab (half = 8)
  const c = Math.cos(theta), s = Math.sin(theta);
  const m = Math.max(Math.abs(c), Math.abs(s)) || 1;
  return [c / m * h - s * lane, s / m * h + c * lane];
}
