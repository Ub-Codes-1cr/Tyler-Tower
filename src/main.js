// Problem 32/35: a chip colour used as a fill (dot / chart bar / accent) must stay visible
// against cream. Darken the hex until it clears ~3:1, leaving the bright chip for tints.
function readableChip(hex) {
  const h = String(hex || '').replace('#', '');
  if (!/^[0-9a-fA-F]{6}$/.test(h)) return hex || '#6366F1';
  const p = i => parseInt(h.slice(i, i + 2), 16);
  const lum = (r, g, b) => {
    const a = [r, g, b].map(v => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); });
    return 0.2126 * a[0] + 0.7152 * a[1] + 0.0722 * a[2];
  };
  let [r, g, b] = [p(0), p(2), p(4)];
  const cream = 0.997;
  for (let k = 0; k < 10; k++) {
    const cr = (cream + 0.05) / (lum(r, g, b) + 0.05);
    if (cr >= 3) break;
    r = Math.round(r * 0.85); g = Math.round(g * 0.85); b = Math.round(b * 0.85);
  }
  const hx = v => v.toString(16).padStart(2, '0');
  return '#' + hx(r) + hx(g) + hx(b);
}
