// show exactly one division's cards; everything else hides. Unknown division = hide all.
// Wrapped defensively: one malformed card must never take the whole reveal engine down.
function setDivisionCardsVisible(div) {
  try {
    const nodes = divisionCards();
    let shown = 0;
    for (const el of nodes) {
      const match = !!div && el.getAttribute('data-division') === div;
      el.classList.toggle('visible', match);
      el.style.visibility = match ? 'visible' : 'hidden';
      el.style.opacity = match ? '1' : '0';
      el.style.pointerEvents = match ? 'auto' : 'none';
      // a hidden card must not be a tab stop; a revealed one must be (Phase 6 / Problem 21)
      el.querySelectorAll('button, input, [tabindex]').forEach(f => {
        if (!f.hasAttribute('data-tab-fixed')) f.tabIndex = match ? 0 : -1;
      });
      if (match) shown++;
    }
    // the badge/pill that owns this division gets a lit state too
    for (const b of document.querySelectorAll('.badge.bench[data-division]')) {
      b.classList.toggle('revealed', !!div && b.dataset.division === div);
      b.setAttribute('aria-expanded', !!div && b.dataset.division === div ? 'true' : 'false');
    }
    return shown;
  } catch (e) {
    console.warn('division reveal:', e && e.message);
    return 0;
  }
}

function hideAllDivisionCards(restoreFocus = false) {
  activeDivision = null;
  setDivisionCardsVisible(null);
  const src = lastRevealSource;
  lastRevealSource = null;
  if (restoreFocus && src && src.isConnected) {
    // focus events fire synchronously inside .focus(), so guard with a plain flag and clear it
    // the moment .focus() returns. Using requestAnimationFrame here let the heavy 3D loop starve
    // the reset, which then swallowed the user's next hover/click reveal.
    suppressReveal = true;
    try { src.focus({ preventScroll: true }); } catch { /* element gone */ }
    suppressReveal = false;
  }
}

// the one entry point: hovering OR focusing any division target reveals it
function revealDivision(div, sourceEl) {
  if (!div || suppressReveal) return;
  clearTimeout(hideTimer);              // a new hover always cancels the pending hide (Problem 7)
  if (sourceEl) lastRevealSource = sourceEl;
  // even when this division is already active, re-apply: the roster may have just been
  // repainted, so freshly-created cards still need the visible class (Problem 5 + 40)
  if (activeDivision !== div) activeDivision = div;
  setDivisionCardsVisible(div);
}

// leaving a target schedules the hide; a grace window lets the pointer travel onto the cards
function scheduleHide() {
  clearTimeout(hideTimer);
  hideTimer = setTimeout(() => {
    // stay revealed while the pointer sits on a card of the active division
    const on = document.querySelector('.division-card.visible:hover, .badge.bench.revealed:hover');
    if (on) { scheduleHide(); return; }
    hideAllDivisionCards();
  }, DIVISION_HOVER_GRACE);
}

