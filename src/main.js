// Problem 23: turn a raw server/HTTP failure into something an owner can act on.
function friendlyTaskError(msg) {
  const m = String(msg || '');
  if (/claude.*not (found|installed)|not found on PATH/i.test(m))
    return "Claude Code isn't running on this machine — install it and restart the office, then retry";
  if (/not signed in|unauthor|401|auth/i.test(m)) return "Claude Code needs signing in again — run `claude` in a terminal and log in";
  if (/fetch|network|Failed to fetch|ENOTFOUND|ECONNREFUSED/i.test(m)) return "the office server isn't answering — check it is still running";
  if (/400|bad request|invalid/i.test(m)) return 'the office rejected that goal — try rewording it';
  return m.length > 90 ? m.slice(0, 90) + '…' : m;
}
function wirePodRows(root) {
  // Problem 38/40: delegation. The roster is repainted on every search keystroke and every
  // "show all", so per-row listeners were orphaned each time. One listener on the container
  // survives every repaint; rows are found via closest('.prow'). The flag lives on the element
  // so a rebuilt `#podRows` gets its own listener.
  if (root.dataset.podWired) return;
  root.dataset.podWired = '1';
  root.addEventListener('click', (e) => {
    const row = e.target.closest && e.target.closest('.prow');
    if (!row || !root.contains(row)) return;
    const slug = row.dataset.slug;
    if (e.target.closest('.pr-chat')) {
      e.stopPropagation();
      revealDivision(row.dataset.division, row);
      openCitizenChat(slug);
      return;
    }
    if (e.target.closest('.pr-deploy')) {
      e.stopPropagation();
      revealDivision(row.dataset.division, row);
      const go = row.querySelector('.pr-go');
      go.hidden = !go.hidden;
      e.target.closest('.pr-deploy').setAttribute('aria-expanded', go.hidden ? 'false' : 'true');
      if (!go.hidden) go.querySelector('input').focus();
      return;
    }
    const goBtn = e.target.closest('.pr-go button');
    if (goBtn) { e.stopPropagation(); submitPodGoal(row, goBtn); }
  });
}
function submitPodGoal(row, btn) {
  const slug = row.dataset.slug;
  const c = getCitizen(slug);
  const input = row.querySelector('.pr-go input');
  const goal = input.value.trim().replace(/\s+/g, ' ').slice(0, 600);
  const st = row.querySelector('.pr-status');
  // Problem 22: a real goal, not two letters
  if (!c) { st.textContent = 'unknown skill'; return; }
  if (goal.length < 5) { st.textContent = 'describe the goal (min 5 characters)'; input.focus(); return; }
  // Problem 24: one deploy in flight per row — the button is disabled until it settles
  if (row.dataset.busy) return;
  row.dataset.busy = '1';
  row.classList.add('busy');
  st.className = 'pr-status busy';
  st.textContent = 'sending…';
  btn.disabled = true; input.disabled = true;
  const reset = () => { delete row.dataset.busy; row.classList.remove('busy'); btn.disabled = false; input.disabled = false; };
  fetch('/api/tasks', { method: 'POST', headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ dept: deptFor(c.division), text: `Skill aa-${slug} (${c.name}): ${goal}` }) })
    .then(async res => { if (!res.ok) throw new Error((await res.json().catch(() => ({}))).error || res.statusText); return res.json(); })
    .then(t => {
      reset();
      const who = (t.agent && R[t.agent] ? R[t.agent].name : t.agent) || 'the desk';
      // Problem 46: the result is a link to the board so the owner can watch it land
      st.className = 'pr-status ok';
      st.innerHTML = `✓ sent to ${esc(String(who))} <button class="pr-open" type="button">open board</button>`;
      st.querySelector('.pr-open').addEventListener('click', (ev) => {
        ev.stopPropagation();
        if (tasks && tasks.toggle) tasks.toggle();
      });
      row.querySelector('.pr-go').hidden = true;
      // the citizen's plate just changed — repaint it if its chat is open
      try { if (modalOpen === slug) renderChat(slug); } catch {}
    })
    .catch(e => {
      reset();
      st.className = 'pr-status err';
      st.textContent = friendlyTaskError(e.message);
      st.title = String(e.message || '');   // the raw message stays available for debugging
    });
}
