function setRoute(route, opts = {}) {
  const { updateHistory = true } = opts;
  const tpanel = document.getElementById('tpanel');
  const connOv = document.getElementById('connectorsOv');
  const apprOv = document.getElementById('approvalsOv');
  const settOv = document.getElementById('settingsOv');

  // Synchronize active rail pill state
  document.querySelectorAll('#rail-nav .nav-item').forEach(btn => {
    btn.classList.toggle('is-on', btn.dataset.nav === route);
  });

  if (updateHistory && typeof history !== 'undefined') {
    const targetPath = route === 'home' ? '/' : '/' + route;
    if (window.location.pathname !== targetPath) {
      history.pushState({ route }, '', targetPath);
    }
  }

  switch (route) {
    case 'home':
      closeAllModals();
      zoomOut();
      break;
    case 'connectors':
      closeAllModals();
      if (connOv) {
        connOv.classList.add('on');
        document.body.classList.add('modalOpen');
      }
      break;
    case 'brain':
      closeAllModals();
      if (brain && typeof brain.open === 'function') brain.open();
      break;
    case 'board':
      closeAllModals();
      if (tasks && typeof tasks.open === 'function') tasks.open();
      break;
    case 'tasks':
      closeAllModals();
      if (tpanel) {
        if (tpanel.classList.contains('collapsed')) {
          tpanel.classList.remove('collapsed');
          document.body.classList.remove('tp-collapsed');
          const btn = document.getElementById('tpToggleBtn');
          if (btn) btn.textContent = '◀';
          try { localStorage.setItem('tyler_tpanel_collapsed', '0'); } catch {}
        }
      }
      break;
    case 'calendar':
      closeAllModals();
      if (tasks && tasks.calendar && typeof tasks.calendar.open === 'function') tasks.calendar.open();
      break;
    case 'approvals':
      closeAllModals();
      if (apprOv) {
        apprOv.classList.add('on');
        document.body.classList.add('modalOpen');
      }
      break;
    case 'camera':
      setCam(!document.body.classList.contains('cam'));
      break;
    case 'settings':
      closeAllModals();
      if (settOv) {
        settOv.classList.add('on');
        document.body.classList.add('modalOpen');
      }
      break;
  }
}
